"""Regenerate nsbench/core.py from the main notebook, so stage notebooks reuse the exact same
models, Trainer and SpectralLoss. Run after editing those notebook cells:

    python tools/build_nsbench.py
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
NB = ROOT / "navier-stokes.ipynb"
OUT = ROOT / "nsbench" / "core.py"

# (marker that identifies the cell, lines to drop)
CELLS = [
    ("def FourierNeuralOperator", []),
    ("def Cnn", []),
    ("class UNet", [r"^model = UNet\(\)$"]),
    ("def _tensor_bytes", []),
    ("class Trainer", []),
    ("class SpectralLoss", [r"^print\(f\"\[INFO\] SpectralLoss", r"^      f\"\{SpectralLoss"]),
]


def main():
    cells = [("".join(c["source"])) for c in json.loads(NB.read_text())["cells"] if c["cell_type"] == "code"]
    parts = ['"""Generated by tools/build_nsbench.py from navier-stokes.ipynb. Do not edit by hand."""',
             "import time, copy", "import pandas as pd", "import torch, torch.nn as nn",
             "from tqdm.auto import tqdm", "from neuralop.models import FNO", ""]
    for marker, drop in CELLS:
        src = next(s for s in cells if marker in s)
        lines = [l for l in src.splitlines() if not any(re.match(d, l) for d in drop)]
        parts.append(f"# ---- from notebook cell containing `{marker}`")
        parts.append("\n".join(lines).rstrip() + "\n")
    OUT.write_text("\n".join(parts))
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
